/* GCF-400 v27 — layout, copy and responsive security verification. */
'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const FP='ab12cd34'.repeat(8);
const nodes=new Map();
const node=id=>{if(!nodes.has(id))nodes.set(id,{id,hidden:false,textContent:'',dataset:{},disabled:false});return nodes.get(id);};
globalThis.document={getElementById:node};
let clipboard='';
Object.defineProperty(globalThis,'navigator',{value:{clipboard:{writeText:async t=>{clipboard=t;}}},configurable:true});
const UI=require('../security-ui.js');
assert.equal(UI.formatFingerprint(FP),Array(8).fill('ab12cd34').join(' '));
assert.equal(UI.formatFingerprint('bad'),'');
assert.equal(UI.formatFingerprint('<img src=x>'),'');
UI.keyStatus({message:'Key created',fingerprint:FP,state:'success'});
assert.equal(node('deviceSignerStatus').textContent,'Key created');
assert.equal(node('deviceSignerStatus').dataset.state,'success');
assert.equal(node('deviceFingerprintPanel').hidden,false);
assert.equal(node('deviceFingerprintValue').textContent,Array(8).fill('ab12cd34').join(' '));
assert.equal(node('copyDeviceFingerprint').dataset.value,FP);
(async()=>{
 assert.equal(await UI.copyFingerprint(),true);
 assert.equal(clipboard,FP,'Copy must preserve the unspaced 64-character value');
 assert.match(node('deviceCopyStatus').textContent,/copied/i);
 UI.verificationStatus({message:'Signature valid',fingerprint:FP,digest:'ff'.repeat(32),state:'success',sourceResult:'Matches',trustResult:'Trusted'});
 assert.equal(node('verificationDetails').hidden,false);
 assert.equal(node('verificationFingerprintValue').textContent,Array(8).fill('ab12cd34').join(' '));
 assert.equal(node('verificationHashValue').textContent,Array(8).fill('ffffffff').join(' '));
 assert.equal(node('verificationSourceValue').textContent,'Matches');
 assert.equal(node('verificationTrustValue').textContent,'Trusted');
 UI.keyStatus({message:'Key erased',state:'warning'});
 assert.equal(node('deviceFingerprintPanel').hidden,true);
 assert.equal(node('deviceFingerprintValue').textContent,'');
 UI.verificationStatus({message:'Selection cleared'});
 assert.equal(node('verificationDetails').hidden,true);
 const html=fs.readFileSync(path.join(__dirname,'../index.html'),'utf8');
 const css=html.slice(html.indexOf('/* v28 simplified task-centered layout'));
 assert.ok(css.includes('overflow-wrap:anywhere'),'Long fingerprints must wrap inside the card');
 assert.ok(css.includes('.security-hex'),'Monospace fingerprint styling must be present');
 assert.ok(css.includes('@media(max-width:720px)')&&css.includes('@media(max-width:640px)'),'Mobile layout must be supported');
 assert.ok(html.includes('id="deviceFingerprintValue"'));
 assert.ok(html.includes('id="copyDeviceFingerprint"'));
 assert.ok(html.includes('id="verificationFingerprintValue"'));
 assert.ok(html.includes('id="verificationHashValue"'));
 assert.ok(html.includes('class="card tool-drawer"'),'Security tools must be an optional disclosure');
 assert.ok(html.includes('class="audit-verify"'),'Verifier must be collapsible');
 assert.ok(html.includes('class="audit-advanced"'),'Advanced trust control must be collapsible');
 assert.ok(html.indexOf('id="verifyEvidenceFile"')<html.indexOf('id="results"'),'Verifier should be available without a scan');
 assert.ok(html.includes('id="offlineApplyUpdate"'),'Update ready button is required');
 const currentMarkup=html.slice(html.indexOf('<section class="card audit-security"'),html.indexOf('id="results"'));
 assert.ok(!currentMarkup.includes('Public SHA-256 fingerprint:'),'Old overflowing text must not appear in markup');
 assert.equal((html.match(/id="deviceSignerStatus"/g)||[]).length,1);
 assert.equal((html.match(/id="deviceFingerprintValue"/g)||[]).length,1);
 assert.equal((html.match(/id="verifyEvidenceStatus"/g)||[]).length,1);
 const app=fs.readFileSync(path.join(__dirname,'../audit-app.js'),'utf8');
 assert.ok(app.includes('GCFSecurityUI.keyStatus'));
 assert.ok(app.includes('GCFSecurityUI.verificationStatus'));
 assert.ok(!app.includes("'Public SHA-256 fingerprint: '+r.fingerprint"),'Never print raw fingerprint in paragraph');
 console.log('GCF security layout PASS: grouping, copy, mobile wrap CSS, state changes and independent verifier display.');
})().catch(e=>{console.error(e);process.exitCode=1;});
